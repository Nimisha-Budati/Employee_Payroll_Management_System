from django.contrib.auth.models import User
from django.db import models
from accounts.models import Company


class AIKnowledgeBase(models.Model):
    """Organisation-specific text the AI assistants may quote (single row, edited by administrators)."""

    company = models.ForeignKey(Company, null=True, on_delete=models.CASCADE, related_name='ai_knowledge_bases')
    company_overview = models.TextField(blank=True)
    leave_policy = models.TextField(blank=True)
    faq = models.TextField(blank=True)
    updated_by = models.ForeignKey(User, on_delete=models.SET_NULL, null=True, blank=True, related_name='+')
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        constraints = [models.UniqueConstraint(fields=['company'], name='one_ai_knowledge_per_company')]

    @classmethod
    def load(cls, company=None):
        if company is None:
            return cls.objects.filter(company__isnull=True).first() or cls.objects.create(company=None)
        return cls.objects.get_or_create(company=company)[0]


class AIConversation(models.Model):
    CHAT, LEAVE, SALARY, ATTENDANCE = 'CHAT', 'LEAVE', 'SALARY', 'ATTENDANCE'
    FEATURE_CHOICES = [
        (CHAT, 'AI chatbot'),
        (LEAVE, 'Leave policy assistant'),
        (SALARY, 'Salary breakdown assistant'),
        (ATTENDANCE, 'Attendance insights'),
    ]
    SCOPE_CHOICES = [('SELF', 'Own data'), ('EMPLOYEE', 'One employee'), ('COMPANY', 'Whole company')]

    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name='ai_conversations')
    feature = models.CharField(max_length=12, choices=FEATURE_CHOICES)
    title = models.CharField(max_length=120, blank=True)
    # Administrators may ask about one employee (salary / attendance); employees always use their own data.
    scope = models.CharField(max_length=10, choices=SCOPE_CHOICES, default='SELF')
    subject = models.ForeignKey(User, on_delete=models.CASCADE, null=True, blank=True, related_name='+')
    payslip = models.ForeignKey('payroll.Payslip', on_delete=models.SET_NULL, null=True, blank=True, related_name='+')
    period_start = models.DateField(null=True, blank=True)
    period_end = models.DateField(null=True, blank=True)
    # Pinned conversations are listed first, most recently pinned on top; the title can be renamed by its owner.
    pinned = models.BooleanField(default=False)
    pinned_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = [models.F('pinned').desc(), models.F('pinned_at').desc(nulls_last=True), '-updated_at', '-id']
        indexes = [models.Index(fields=['user', 'pinned', 'updated_at'])]

    def __str__(self):
        return f'{self.user.username}: {self.get_feature_display()} – {self.title}'


class AIMessage(models.Model):
    ROLE_CHOICES = [('user', 'User'), ('assistant', 'Assistant')]
    MODE_CHOICES = [
        ('AI', 'Generated by Gemini from retrieved data'),
        ('DATA', 'Records shown directly because the AI service was unavailable'),
        ('REFUSAL', 'Request for another person\'s data refused by PayrollPro'),
    ]

    conversation = models.ForeignKey(AIConversation, on_delete=models.CASCADE, related_name='messages')
    role = models.CharField(max_length=10, choices=ROLE_CHOICES)
    content = models.TextField()
    mode = models.CharField(max_length=10, choices=MODE_CHOICES, default='AI')
    # Short labels of the records and knowledge topics used for an answer, e.g. "Payslip September 2026 (paid)".
    sources = models.JSONField(default=list, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['created_at', 'id']
